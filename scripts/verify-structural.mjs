import { PDFDocument } from "pdf-lib";
import { writeFileSync } from "node:fs";
import { structuralPdfEngine } from "../packages/engine-structural/dist/index.js";

const seed = await PDFDocument.create();
seed.addPage([300, 400]);
seed.addPage([500, 600]);
const source = await seed.save();
const engine = await structuralPdfEngine.open(source);
if (engine.pageCount() !== 2) throw new Error("initial page count");
await engine.insertBlankPage(1, 200, 200);
await engine.duplicatePages([0]);
if (engine.pageCount() !== 4) throw new Error("insert/duplicate page count");
await engine.rotatePages([0, 2], 90);
await engine.reorderPages([3, 2, 1, 0]);
const extracted = await engine.extractPages([0, 1]);
const extractedDoc = await PDFDocument.load(extracted);
if (extractedDoc.getPageCount() !== 2) throw new Error("extract page count");
const split = await engine.split([{ start: 0, end: 1 }, { start: 2, end: 3 }]);
if (split.length !== 2 || (await PDFDocument.load(split[0])).getPageCount() !== 2) throw new Error("split output");
const merged = await PDFDocument.create();
merged.addPage([100, 100]);
await engine.merge([await merged.save()]);
if (engine.pageCount() !== 5) throw new Error("merge page count");
await engine.addTextWatermark("CONFIDENCIAL", [0, 1]);
await engine.addPageNumbers("Página {page}/{total}");
await engine.attachFile(new Uint8Array([1, 2, 3]), "evidence.bin", "PoC attachment", "application/octet-stream");
const attachedBytes = await engine.save({ compressed: true });
const attachmentEngine = await structuralPdfEngine.open(attachedBytes);
if (!(await attachmentEngine.removeAttachment("evidence.bin"))) throw new Error("attachment removal failed");
await attachmentEngine.attachFile(new Uint8Array([1, 2, 3]), "evidence.bin", "PoC attachment", "application/octet-stream");
await attachmentEngine.createTextField("customerName", 0, { x: 72, y: 640, width: 220, height: 24 }, "Demo");
await attachmentEngine.setBookmarks([{ title: "Inicio", pageIndex: 0 }, { title: "Segunda", pageIndex: 1 }]);
await attachmentEngine.addHeaderFooter("Enterprise PDF Editor", "Página {page}");
const pixel = Uint8Array.from(Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=", "base64"));
await attachmentEngine.insertImage(pixel, 0, { x: 240, y: 320, width: 24, height: 24 }, "image/png");
await attachmentEngine.addNativeLink("external-link", 0, { x: 72, y: 600, width: 120, height: 24 }, { kind: "url", url: "https://example.com" });
await attachmentEngine.addNativeLink("internal-link", 0, { x: 72, y: 560, width: 120, height: 24 }, { kind: "page", pageIndex: 1 });
if (!(await attachmentEngine.removeNativeLink("external-link"))) throw new Error("link removal failed");
await attachmentEngine.addNativeLink("external-link", 0, { x: 72, y: 600, width: 120, height: 24 }, { kind: "url", url: "https://example.com" });
const compressed = await attachmentEngine.save({ compressed: true });
writeFileSync("tmp-structural-poc.pdf", compressed);
if (compressed.length === 0) throw new Error("empty output");
if ((await PDFDocument.load(compressed)).getForm().getFields().length !== 1) throw new Error("AcroForm field missing");
console.log(JSON.stringify({ pageCount: attachmentEngine.pageCount(), extractedBytes: extracted.length, splitCount: split.length, compressedBytes: compressed.length }));

